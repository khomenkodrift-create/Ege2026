ans = []
for N in range(1, 100_000):
    R = f'{N:b}' # или bin(N)[2:]
    if R.count('1') % 2 == 0:
        R = '10' + R[2:] + '0' # два левых разряда на 10 - '10' + R[2:] и справа приписать 0 - + '0'
    else:
        R = '11' + R[2:] + '1' # два левых разряда на 10 - '11' + R[2:] и справа приписать 0 - + '1'

    R = int(R, 2) # переводим R из 2 системы
    if R >= 16:
        ans.append(N)
print(min(ans))