from functools import lru_cache
@lru_cache(None)
def F(n): #15 -> 31054
    if n < 31054: return F(n + 4) + 3020
    return 3 * (G(n - 2) - 15)
@lru_cache(None)
def G(n): #27 (тк >= 28) ->
    if n >= 28: return G(n - 5) - 15
    return 3 * n - 4

for i in range(27, 31053):
    G(i)

for i in range(31054, 15, -1):
    F(i)

print(F(15))
#Анализ функций F(n) и G(n)
#G(n):
#Базовый случай: при n≥28, вызывается рекурсия с n - 5.
#Общее:
#для n<28: G(n)=3n−4.
#для n≥28: G(n)=G(n−5)−15.
#Это цепочка рекурсий, которая (по сути) уменьшает n на 5, пока не достигнет 28, и затем использует линейную формулу.

#F(n):
#Базовый случай: если n<31054, вызывает F(n + 4) + 3020.
#Иначе: возвращает 3×(G(n−2)−15).
#Обратное движение: для n<31054 вызывает рекурсию с увеличением n на 4, а для n \geq 31054 — использует G(n-2).

#В чем суть вызовов?
#В цикле for i in range(27, 31053): G(i) — вызываются все G(i) с 27 до 31052, чтобы мемоизация запомнила их значения.
#В цикле for i in range(31054, 15, -1): F(i) — вызываются F(i) с 31054 по 16 по убыванию (от 31054 до 16).
#Значение print(F(15)) — это итоговая результат работы функций.

#Что делает этот код?
#Он вызывает рекурсивные функции с мемоизацией для вычисления значения F(15).
#Объекты вызываются с большими n для кеширования — чтобы избежать повторных расчетов.
#Что можно сказать?
#Эта схема — часто используемый приём для вычислений рекурсивных функций при больших диапазонах.
#В данном случае конечный результат — F(15) после всех вычислений.